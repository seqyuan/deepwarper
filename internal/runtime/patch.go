package runtime

import "fmt"

// RuntimePatch renders the dsh runtime patch that points the workspace
// controller at the instance's workspace.
//
// The argument must be a path that exists on the host running `dw instance`.
// For the local backend that is the host workspace directory; for SGE it is the
// workspace *box* (`/workspace`), because the container binds the host
// workspace there and the host path does not exist inside it.
func RuntimePatch(workspaceDir string) string {
	return fmt.Sprintf(`# generated by dw
- id: workspace-controller
  config:
    documentsDirectory: %s
- id: working-directory
  config:
    defaultDirectory: %s
`, workspaceDir, workspaceDir)
}
