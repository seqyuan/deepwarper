package runtime

import "fmt"

// RuntimePatch renders the dsh runtime patch that points the workspace
// controller at the workspace path dsh will see.
func RuntimePatch(workspaceDir string) string {
	return fmt.Sprintf(`# generated by dw
- id: workspace-controller
  config:
    documentsDirectory: %s
- id: working-directory
  config:
    defaultDirectory: %s
`, workspaceDir, workspaceDir)
}
